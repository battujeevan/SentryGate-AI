func sectionEnvironment(w *writer, withEvidence []Row) {
	w.p("## 3. Tested Environment")
	w.nl()
	if len(withEvidence) == 0 {
		w.p("%s: no evidence, so no environment was recorded.", PhraseNotTested)
		w.nl()
		return
	}
	groups := map[string][]string{}
	envs := map[string]map[string]any{}
	for _, r := range withEvidence {
		key := fmt.Sprint(sortedPairs(r.Result.Environment))
		groups[key] = append(groups[key], r.TestID)
		envs[key] = r.Result.Environment
	}
	keys := make([]string, 0, len(groups))
	for k := range groups {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		w.p("Recorded in the evidence of %s:", strings.Join(groups[k], ", "))
		w.nl()
		var rows [][]string
		for _, kv := range sortedPairs(envs[k]) {
			rows = append(rows, []string{kv[0], kv[1]})
		}
		w.table([]string{"Property", "Value"}, rows)
	}
	w.p("F5 components present: **none**. The harness neither starts nor simulates any F5 component.")
	w.nl()
}

func sortedPairs(m map[string]any) [][2]string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := make([][2]string, 0, len(keys))
	for _, k := range keys {
		out = append(out, [2]string{k, fmt.Sprint(m[k])})
	}
	return out
}

