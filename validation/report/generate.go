func f5Wording(r Row) string {
	if r.Result == nil {
		return PhraseNotTested
	}
	switch r.F5Result {
	case f5.ResultNotTested:
		return PhraseNotTested + " — no F5 component was in the request path; no F5 behavior was observed."
	case f5.ResultNotApplicable:
		return "NOT APPLICABLE — the attack requests in this test go directly to the execution boundary and pass through no gateway in front of ingress."
	case f5.ResultUnknown:
		return PhraseUnknown
	case f5.ResultPrevented:
		if r.Result.Kind == evidence.KindAttack {
			return PhraseF5Prevented
		}
		return "F5 denied a legitimate request in this test. This is an observation of the tested configuration, not a finding by itself."
	case f5.ResultAllowed:
		if r.Result.Kind != evidence.KindAttack {
			return "F5 allowed the legitimate request(s), as expected."
		}
		switch r.SentryGateResult {
		case evidence.SGBlocked:
			return PhraseF5AllowedSGBlk
		case evidence.SGDidNotBlock:
			return "F5 allowed the tested request and SentryGate did not block execution. This records what was observed in the tested configuration; it is not a vulnerability finding unless a reproducible security defect is demonstrated and analysed."
		}
		return "F5 allowed the tested request; SentryGate result: " + r.SentryGateResult + "."
	}
	return PhraseUnknown
}

func sgWording(r Row) string {
	res := r.Result
	switch r.SentryGateResult {
	case evidence.SGBlocked:
		return "SentryGate refused every attack request in this test."
	case evidence.SGDidNotBlock:
		var labels []string
		for _, a := range res.Attempts {
			if a.Role == "attack" && a.SentryGate == "EXECUTED" {
				labels = append(labels, "\""+a.Label+"\"")
			}
		}
		return "At least one attack request executed: " + strings.Join(labels, ", ") + "."
	case evidence.SGExecuted:
		return "SentryGate allowed and executed the legitimate request(s)."
	case evidence.SGNotExecuted:
		return "The legitimate request(s) did not execute."
	case evidence.SGNotApplicable:
		return "No request of the relevant role."
	}
	return PhraseUnknown
}

func sectionResults(w *writer, rows []Row) {
	w.p("## 8. Results")
	w.nl()
	for _, r := range rows {
		w.p("### %s %s: %s", r.TestID, r.TestName, r.Status)
		w.nl()
		if r.Result == nil {
			w.p("%s. No evidence.", PhraseNotTested)
			w.nl()
			continue
		}
		res := r.Result
		if res.BlockedReason != "" {
			w.p("**BLOCKED:** %s", res.BlockedReason)
			w.nl()
		}
		w.p("- **F5 (layer 1):** `%s`. %s", r.F5Result, f5Wording(r))
		w.p("- **SentryGate (layer 2):** `%s`. %s", r.SentryGateResult, sgWording(r))
		w.p("- **Infrastructure (layer 3):** `%s`: %d tools/call invocation(s), %d mutation(s), expected %d.", r.InfrastructureResult, res.Invocations, res.MutationCount, res.ExpectedMutations)
		w.p("- **Run:** %s to %s. Evidence: `%s`.", res.StartedAt, res.FinishedAt, res.EvidencePath)
		w.nl()
		if len(res.Attempts) > 0 {
			var tr [][]string
			for _, a := range res.Attempts {
				f5d := a.F5Decision
				if f5d == "" {
					f5d = "-"
				} else {
					f5d += " (" + a.F5Source + ")"
				}
				tt := "-"
				if a.Tool != "" {
					tt = a.Tool + " / " + a.Target
				}
				tr = append(tr, []string{a.Label, a.Role, a.Path, a.AgentID, tt, f5d, strings.TrimSpace(a.SentryGate + " " + a.SentryGateDetail)})
			}
			w.table([]string{"Request", "Role", "Path", "Agent", "Tool / target", "F5 decision (source)", "SentryGate outcome"}, tr)
		}
		if len(res.Checks) > 0 {
			var cr [][]string
			for _, c := range res.Checks {
				cr = append(cr, []string{c.Name, c.Expected, c.Observed, c.Result})
			}
			w.table([]string{"Check", "Expected", "Observed", "Result"}, cr)
		}
		for _, n := range res.Notes {
			w.p("- Note: %s", n)
		}
		if len(res.Notes) > 0 {
			w.nl()
		}
	}
}

