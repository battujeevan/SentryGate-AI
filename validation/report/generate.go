	w.p("## 2. Scope")
	w.nl()
	w.p("**System under test:** F5 AI Gateway / F5 MCP Gateway, as the authorization layer between an AI agent and the tools it calls.")
	w.nl()
	w.p("**Complementary control:** SentryGate-AI, an independent execution-boundary control. It is not a replacement for F5 and is not evaluated as one; it is present so that each test can show, separately, what the gateway decided, what SentryGate decided, and what actually happened to the infrastructure.")
	w.nl()
	w.p("**In scope:** the authorization-to-execution path for MCP tool calls: whether an operation that was authorized is the operation that executes, executes at most once, executes only under current policy, and executes only for the authenticated identity. Twelve scenarios (TC01-TC12) cover legitimate use, substitution of tool, target, arguments and identity, replay, concurrency, workflow reset, lost responses, forged authorizations and privilege escalation.")
	w.nl()
	w.p("**Out of scope:** prompt-injection and content inspection, model behavior, F5 features other than authorization of tool calls, performance, availability, and any production deployment. The agent is deterministic (no LLM).")
