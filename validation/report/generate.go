func sectionRecommendations(w *writer, rows []Row, f5Observed bool) {
	w.p("## 13. Recommendations")
	w.nl()
	if !f5Observed {
		w.p("**To obtain F5 results:**")
		w.nl()
		w.p("1. Deploy F5 AI Gateway and/or F5 MCP Gateway at insertion point A (in front of SentryGate ingress, `-ingress-url`) and/or B (in front of the test MCP server, `-worker-mcp-url`, with `-mcp-listen` fixing the test server's address).")
		w.p("2. Implement `f5.F5ObservationProvider` against F5's documented audit or logging interface, populating every field from real F5 records and leaving `MockedFields` empty.")
		w.p("3. Re-run `go run ./validation/cmd/f5validate -tc all -f5-provider <provider>` and regenerate this report. Only then can an F5 result other than %s appear.", PhraseNotTested)
		w.nl()
	}
	var recs []string
	for _, r := range rows {
		if r.Result == nil {
			continue
		}
		covered := false
		for _, rec := range recommendations {
			if rec.testID == r.TestID && applies(rec, r.Result) {
				recs = append(recs, fmt.Sprintf("- **%s (SentryGate-AI):** %s", r.TestID, rec.text))
				covered = true
			}
		}
		if r.Status == evidence.StatusFailed && !covered {
			recs = append(recs, fmt.Sprintf("- **%s:** investigate the failed checks in section 8 before relying on the control this test covers.", r.TestID))
		}
	}
	for _, r := range rows {
		if r.Status == evidence.StatusBlocked {
			recs = append(recs, fmt.Sprintf("- **%s:** BLOCKED; resolve the environment problem (%s) and re-run.", r.TestID, r.Result.BlockedReason))
		}
	}
	if len(recs) > 0 {
		w.p("**From the evidence:**")
		w.nl()
		for _, r := range recs {
			w.p("%s", r)
		}
		w.nl()
	}
}

func applies(rec recommendation, res *evidence.Result) bool {
	if rec.failedCheck != "" {
		for _, c := range res.Checks {
			if c.Result == evidence.CheckFail && strings.HasPrefix(c.Name, rec.failedCheck) {
				return true
			}
		}
	}
	if rec.note != "" {
		for _, n := range res.Notes {
			if strings.Contains(n, rec.note) {
				return true
			}
		}
	}
	return false
}

