func sectionLimitations(w *writer, rows []Row, f5Observed bool) {
	w.p("## 12. Limitations")
	w.nl()
	if !f5Observed {
		w.p("- **No F5 component was tested.** Every F5 result is %s or NOT_APPLICABLE. The harness has an F5 observation boundary (`validation/f5`) but no provider for a real F5 deployment yet.", PhraseNotTested)
	}
	w.p("- The infrastructure is a test MCP server with a disposable SQLite database, not a production system. Its status tool (`sentrygate_execution_status`) exists so reconciliation can be exercised; production MCP servers may offer nothing equivalent.")
	w.p("- The agent is deterministic and sends exactly the requests each test defines. No LLM, prompt or content-level behavior is tested.")
	w.p("- Temporal runs as the CLI dev server (in-memory, single process). Clustered deployments, persistence failures and network partitions are not tested.")
	w.p("- Each test is one run. Timing-dependent behavior (concurrency, reset during dispatch) was observed in that run; a single run does not prove it under all interleavings.")
	w.p("- Process stops are abrupt kills (the harness cannot send a graceful signal on every platform).")
	seen := map[string]bool{}
	for _, r := range rows {
		if r.Result == nil {
			continue
		}
		for _, l := range r.Result.Limitations {
			if !seen[l] {
				seen[l] = true
				w.p("- %s (%s)", l, r.TestID)
			}
		}
	}
	var missing []string
	for _, r := range rows {
		if r.Result == nil {
			missing = append(missing, r.TestID)
		}
	}
	if len(missing) > 0 {
		w.p("- No evidence for %s; those tests are %s.", strings.Join(missing, ", "), PhraseNotTested)
	}
	w.nl()
}

