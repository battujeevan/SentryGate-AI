// Phrases with fixed meaning in the report.
const (
	PhraseNotTested      = "NOT TESTED"
	PhraseUnknown        = "UNKNOWN — insufficient evidence"
	PhraseF5Prevented    = "VERIFIED — F5 prevented the tested scenario"
	PhraseF5AllowedSGBlk = "F5 allowed the tested request; SentryGate independently blocked execution."
)

// Title is the report's title.
const Title = "F5 AI Gateway — Independent Security Validation"

type writer struct{ b strings.Builder }

func (w *writer) p(format string, args ...any) { fmt.Fprintf(&w.b, format+"\n", args...) }
func (w *writer) nl()                          { w.b.WriteString("\n") }

func cell(s string) string {
	s = strings.ReplaceAll(s, "\r", "")
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

func (w *writer) table(header []string, rows [][]string) {
	w.p("| %s |", strings.Join(header, " | "))
	seps := make([]string, len(header))
	for i := range seps {
		seps[i] = "---"
	}
	w.p("| %s |", strings.Join(seps, " | "))
	for _, r := range rows {
		cs := make([]string, len(r))
		for i, c := range r {
			cs[i] = cell(c)
		}
		w.p("| %s |", strings.Join(cs, " | "))
	}
	w.nl()
}

// Generate renders the report for the given matrix rows.
func Generate(rows []Row) string {
	w := &writer{}
	var withEvidence []Row
	for _, r := range rows {
		if r.Result != nil {
			withEvidence = append(withEvidence, r)
		}
	}
	f5Observed := false
	for _, r := range withEvidence {
		if r.F5Result != f5.ResultNotTested && r.F5Result != f5.ResultNotApplicable {
			f5Observed = true
		}
	}

	w.p("# %s", Title)
	w.nl()
	w.p("Generated by `go run ./validation/cmd/f5report` from the evidence in `validation/evidence/`. Every result below is read from an evidence file; a test without evidence is reported as %s. The report does not depend on when it is generated: the same evidence always produces the same report.", PhraseNotTested)
	w.nl()
	if !f5Observed {
		w.p("> **F5 status: %s.** No F5 component was in the request path of any test in this evidence set, and no F5 observation was recorded. This report makes no statement about how F5 AI Gateway or F5 MCP Gateway behaves. The F5 column shows what the harness observed, which is nothing.", PhraseNotTested)
		w.nl()
	}

	sectionSummary(w, rows, withEvidence, f5Observed)
	sectionScope(w)
	sectionEnvironment(w, withEvidence)
	sectionArchitecture(w, withEvidence)
	sectionMethodology(w)
	sectionSecurityModel(w)
	sectionTestCases(w, rows)
	sectionResults(w, rows)
	sectionMatrix(w, rows)
	sectionAnalysis(w, rows)
	sectionControls(w, withEvidence)
	sectionLimitations(w, rows, f5Observed)
	sectionRecommendations(w, rows, f5Observed)
	sectionEvidenceIndex(w, rows)
	sectionReproduction(w)
	return w.b.String()
}

func countBy(rows []Row, f func(Row) string) [][]string {
	m := map[string]int{}
	for _, r := range rows {
		m[f(r)]++
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := [][]string{}
	for _, k := range keys {
		out = append(out, []string{k, fmt.Sprint(m[k])})
	}
	return out
}

func sectionSummary(w *writer, rows, withEvidence []Row, f5Observed bool) {
	w.p("## 1. Executive Summary")
	w.nl()
	w.p("Tests defined: %d. Tests with evidence: %d.", len(rows), len(withEvidence))
	w.nl()
	if f5Observed {
		w.p("F5 observations were recorded for at least one test. F5 results per test are in section 8; each is reported exactly as classified from those observations.")
	} else {
		w.p("**F5 AI Gateway / MCP Gateway: %s.** The harness ran without F5. F5 results are %s (or NOT_APPLICABLE where a test sends no attack request through a gateway path). Nothing in this report is an F5 result.", PhraseNotTested, PhraseNotTested)
	}
	w.nl()
	w.p("What the evidence does show is the behavior of SentryGate-AI, the complementary control, and of the test infrastructure behind it:")
	w.nl()
	w.table([]string{"Matrix status", "Tests"}, countBy(rows, func(r Row) string { return r.Status }))
	w.table([]string{"SentryGate result", "Tests"}, countBy(withEvidence, func(r Row) string { return r.SentryGateResult }))
	total, expected := 0, 0
	for _, r := range withEvidence {
		if r.Result.Status != evidence.StatusBlocked {
			total += r.Result.MutationCount
			expected += r.Result.ExpectedMutations
		}
	}
	w.p("Infrastructure mutations observed across tests that ran: %d (expected by the tests' definitions: %d).", total, expected)
	w.nl()
	var failed []Row
	for _, r := range rows {
		if r.Status == evidence.StatusFailed || r.Status == evidence.StatusUnknown || r.Status == evidence.StatusBlocked {
			failed = append(failed, r)
		}
	}
	if len(failed) == 0 {
		w.p("Every test with evidence has status VERIFIED: each of its checks passed in the run that produced the evidence.")
	} else {
		w.p("Tests that are not VERIFIED (details in sections 8 and 12):")
		w.nl()
		for _, r := range failed {
			w.p("- **%s %s: %s.** %s", r.TestID, r.TestName, r.Status, firstFailure(r))
		}
	}
	w.nl()
	w.p("A VERIFIED status is a statement about the stack that was run (SentryGate-AI with the test MCP server). While the F5 result is %s it says nothing about F5.", PhraseNotTested)
	w.nl()
}

func firstFailure(r Row) string {
	if r.Result == nil {
		return "No evidence."
	}
	if r.Result.BlockedReason != "" {
		return "Blocked: " + r.Result.BlockedReason
	}
	var parts []string
	for _, c := range r.Result.Checks {
		if c.Result != evidence.CheckPass {
			parts = append(parts, fmt.Sprintf("%s (expected %s; observed %s)", c.Name, c.Expected, c.Observed))
		}
	}
	if len(parts) == 0 {
		return r.Notes
	}
	return "Not passed: " + strings.Join(parts, "; ") + "."
}

